import { connectNative } from './connect-native.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { expect } from '@playwright/test';
const reference = JSON.parse(await readFile('.local/reference-background-results.json', 'utf8'));
const native = await connectNative();
const page = native.contexts().flatMap(c => c.pages()).find(p => p.url().includes('1420'));
const errors = []; page.on('pageerror', error => errors.push(error.message));
await page.reload(); await page.getByRole('button', {name:'Nuevo',exact:true}).waitFor();
await page.evaluate(async id => { const library = await import('/src/services/library.ts'); await library.loadLibrary(); const item = library.useLibrary.getState().data.items.find(item => item.id === id); if (!item) throw Error('No se encuentra el fondo guardado'); const image = item.project.files.find(f => f.content.startsWith('data:image/')); if(image) await library.updateLibraryItem(id,{thumbnail:image.content}); }, reference.libraryId);
await page.getByRole('button', {name:'Biblioteca',exact:true}).click();
await page.getByRole('textbox', {name:'Buscar en biblioteca',exact:true}).fill('Arcane');
const card = page.locator('.library-card').filter({hasText:'Fondo de imagen · Arcane'}).first();
await expect(card).toBeVisible(); await card.getByRole('button',{name:'Abrir',exact:true}).click();
await page.getByRole('button',{name:'Ejecutar',exact:true}).click();
const frame = page.frameLocator('iframe[title="Vista previa del efecto"]');
await expect(frame.locator('.image-background img')).toBeVisible({timeout:30000});
await page.locator('.file-list').getByRole('button',{name:'main.js',exact:true}).click();
const state = await page.evaluate(async () => {
 const {useLab} = await import('/src/stores/lab.ts');
 const invoke = window.__TAURI_INTERNALS__.invoke;
 const [visible,minimized,size] = await Promise.all(['is_visible','is_minimized','outer_size'].map(command => invoke('plugin:window|'+command,{label:'main'}).catch(error => ({notVerified:String(error)}))));
 return {project:useLab.getState().project.name,tauri:!!window.__TAURI_INTERNALS__,title:document.title,visible,minimized,size,outerWidth,outerHeight,errors:useLab.getState().logs.filter(l=>l.level==='error').map(l=>l.message)};
});
state.serverStatus=(await fetch('http://127.0.0.1:1420')).status;
state.image=await frame.locator('img').evaluate(img=>({complete:img.complete,width:img.naturalWidth,height:img.naturalHeight}));
state.pageErrors=errors;
if(state.serverStatus!==200||!state.tauri||!state.image.complete||state.errors.length||errors.length)throw Error('La revisión final detectó errores: '+JSON.stringify(state));
await page.screenshot({path:'.local/Effect-Lab-v0.1.0-revision.png'});
await writeFile('.local/review-state.json',JSON.stringify(state,null,2));
console.log('REVIEW READY:',state);
await native.close();
